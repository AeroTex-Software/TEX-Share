import {
  aesGcmDecrypt,
  aesGcmEncrypt,
  deriveArgon2Key,
  deriveHkdfKey,
  fromBase64,
  fromBase64Url,
  fromHex,
  fromUtf8,
  generateRecoveryKey,
  normalizeRecoveryKey,
  randomBytes,
  toBase64,
  toBase64Url,
  toHex,
  utf8
} from './crypto';

const MAGIC = utf8('TEXE2EE1');
const VERSION = 1;
const HEADER_SIZE = 37;
export const E2EE_CHUNK_SIZE = 1024 * 1024;
const MANIFEST_AAD = utf8('texshare/manifest/v1');
const WRAP_AAD = utf8('texshare/keywrap/v1');
const FILE_INFO = 'texshare/file/v1';

export interface E2EEManifestFile {
  id: string;
  name: string;
  mime: string;
  size: number;
}

export interface E2EEManifestData {
  v: 1;
  title: string;
  description: string;
  type: string;
  linkUrl?: string;
  textContent?: string;
  files: E2EEManifestFile[];
}

export interface E2EEShareCrypto {
  masterKey: Uint8Array;
  keyWrap: string;
  recoveryWrap: string;
  recoveryKey: string;
  keyFragment: string;
}

/** Exact ciphertext size for a container with the given plaintext length. */
export function encryptedSize(plainSize: number): number {
  const chunks = Math.ceil(plainSize / E2EE_CHUNK_SIZE);
  return HEADER_SIZE + plainSize + 32 * (chunks + 1);
}

function writeUint64(view: DataView, offset: number, value: number): void {
  view.setBigUint64(offset, BigInt(Math.max(0, Math.floor(value))), false);
}

function readUint64(view: DataView, offset: number): number {
  const value = view.getBigUint64(offset, false);
  if (value > BigInt(Number.MAX_SAFE_INTEGER)) throw new Error('container_too_large');
  return Number(value);
}

export interface ContainerHeader {
  salt: Uint8Array;
  plainSize: number;
  chunkSize: number;
}

export function parseContainerHeader(header: Uint8Array): ContainerHeader {
  if (header.length !== HEADER_SIZE) throw new Error('invalid_container');
  for (let i = 0; i < MAGIC.length; i++) {
    if (header[i] !== MAGIC[i]) throw new Error('invalid_container');
  }
  if (header[8] !== VERSION) throw new Error('unsupported_container');
  const view = new DataView(header.buffer, header.byteOffset, header.byteLength);
  const salt = header.slice(9, 25);
  const plainSize = readUint64(view, 25);
  const chunkSize = view.getUint32(33, false);
  if (chunkSize < 1 || chunkSize > 16 * 1024 * 1024) throw new Error('invalid_container');
  return { salt, plainSize, chunkSize };
}

export async function containerHeader(blob: Blob): Promise<ContainerHeader> {
  if (blob.size < HEADER_SIZE) throw new Error('invalid_container');
  const head = new Uint8Array(await blob.slice(0, HEADER_SIZE).arrayBuffer());
  return parseContainerHeader(head);
}

/**
 * Streams an encrypted TEXE2EE1 container. The generated bytes are exactly
 * `encryptedSize(blob.size)` long, which lets the upload reserve the correct
 * amount of quota before any ciphertext is produced.
 */
export async function* encryptFileStream(
  blob: Blob,
  masterKey: Uint8Array,
  onProgress?: (plainBytes: number, total: number) => void
): AsyncGenerator<Uint8Array> {
  const salt = randomBytes(16);
  const key = await deriveHkdfKey(masterKey, salt, FILE_INFO);
  const header = new Uint8Array(HEADER_SIZE);
  header.set(MAGIC, 0);
  header[8] = VERSION;
  header.set(salt, 9);
  const view = new DataView(header.buffer);
  writeUint64(view, 25, blob.size);
  view.setUint32(33, E2EE_CHUNK_SIZE, false);
  yield header;

  let offset = 0;
  while (offset < blob.size) {
    const end = Math.min(offset + E2EE_CHUNK_SIZE, blob.size);
    const plain = new Uint8Array(await blob.slice(offset, end).arrayBuffer());
    const sealed = await aesGcmEncrypt(key, plain);
    const record = new Uint8Array(4 + sealed.nonce.length + sealed.data.length);
    new DataView(record.buffer).setUint32(0, plain.length, false);
    record.set(sealed.nonce, 4);
    record.set(sealed.data, 4 + sealed.nonce.length);
    yield record;
    offset = end;
    onProgress?.(offset, blob.size);
  }

  // A zero-length record proves the end of the stream and authenticates it.
  const final = await aesGcmEncrypt(key, new Uint8Array(0));
  const tail = new Uint8Array(4 + final.nonce.length + final.data.length);
  new DataView(tail.buffer).setUint32(0, 0, false);
  tail.set(final.nonce, 4);
  tail.set(final.data, 4 + final.nonce.length);
  yield tail;
}

class BlobCursor {
  private offset = 0;

  constructor(private readonly blob: Blob) {}

  get remaining(): number {
    return this.blob.size - this.offset;
  }

  async read(length: number): Promise<Uint8Array> {
    if (length < 0 || this.offset + length > this.blob.size) throw new Error('invalid_container');
    if (length === 0) return new Uint8Array(0);
    const data = new Uint8Array(await this.blob.slice(this.offset, this.offset + length).arrayBuffer());
    if (data.length !== length) throw new Error('invalid_container');
    this.offset += length;
    return data;
  }
}

export async function* decryptContainerStream(
  blob: Blob,
  masterKey: Uint8Array,
  onProgress?: (plainBytes: number, total: number) => void
): AsyncGenerator<Uint8Array> {
  const header = await containerHeader(blob);
  const key = await deriveHkdfKey(masterKey, header.salt, FILE_INFO);
  const cursor = new BlobCursor(blob);
  await cursor.read(HEADER_SIZE);
  let total = 0;
  for (;;) {
    const lengthBytes = await cursor.read(4);
    const length = new DataView(lengthBytes.buffer).getUint32(0, false);
    const nonce = await cursor.read(12);
    if (length === 0) {
      const tag = await cursor.read(16);
      await aesGcmDecrypt(key, nonce, tag);
      break;
    }
    if (length > header.chunkSize || length > header.plainSize - total) {
      throw new Error('invalid_container');
    }
    const ciphertext = await cursor.read(length + 16);
    const plain = await aesGcmDecrypt(key, nonce, ciphertext);
    if (plain.length !== length) throw new Error('invalid_container');
    total += plain.length;
    onProgress?.(total, header.plainSize);
    yield plain;
  }
  if (total !== header.plainSize) throw new Error('invalid_container');
}

export async function decryptContainerToBlob(blob: Blob, masterKey: Uint8Array): Promise<Blob> {
  const parts: BlobPart[] = [];
  for await (const chunk of decryptContainerStream(blob, masterKey)) {
    parts.push(chunk as unknown as BlobPart);
  }
  return new Blob(parts);
}

export async function encryptManifest(manifest: E2EEManifestData, masterKey: Uint8Array): Promise<string> {
  const key = await deriveHkdfKey(masterKey, utf8('texshare/manifest'), 'texshare/manifest-key/v1');
  const sealed = await aesGcmEncrypt(key, utf8(JSON.stringify(manifest)), MANIFEST_AAD);
  const out = new Uint8Array(1 + sealed.nonce.length + sealed.data.length);
  out[0] = 1;
  out.set(sealed.nonce, 1);
  out.set(sealed.data, 1 + sealed.nonce.length);
  return toBase64(out);
}

export async function decryptManifest(encoded: string, masterKey: Uint8Array): Promise<E2EEManifestData> {
  const raw = fromBase64(encoded);
  if (raw.length < 30 || raw[0] !== 1) throw new Error('invalid_manifest');
  const nonce = raw.slice(1, 13);
  const data = raw.slice(13);
  const key = await deriveHkdfKey(masterKey, utf8('texshare/manifest'), 'texshare/manifest-key/v1');
  const plain = await aesGcmDecrypt(key, nonce, data, MANIFEST_AAD);
  const parsed = JSON.parse(fromUtf8(plain)) as E2EEManifestData;
  if (!parsed || parsed.v !== 1 || !Array.isArray(parsed.files)) throw new Error('invalid_manifest');
  return parsed;
}

interface WrapPayload {
  v: 1;
  kdf: 'argon2id';
  salt: string;
  nonce: string;
  data: string;
}

export async function wrapMasterKey(masterKey: Uint8Array, secret: string): Promise<string> {
  const salt = randomBytes(16);
  const key = await deriveArgon2Key(secret, salt);
  const sealed = await aesGcmEncrypt(key, masterKey, WRAP_AAD);
  const payload: WrapPayload = {
    v: 1,
    kdf: 'argon2id',
    salt: toBase64(salt),
    nonce: toBase64(sealed.nonce),
    data: toBase64(sealed.data)
  };
  return toBase64(utf8(JSON.stringify(payload)));
}

export async function unwrapMasterKey(wrap: string, secret: string): Promise<Uint8Array> {
  const payload = JSON.parse(fromUtf8(fromBase64(wrap))) as WrapPayload;
  if (!payload || payload.v !== 1 || payload.kdf !== 'argon2id') throw new Error('invalid_key_wrap');
  const salt = fromBase64(payload.salt);
  const nonce = fromBase64(payload.nonce);
  const data = fromBase64(payload.data);
  const key = await deriveArgon2Key(secret, salt);
  const master = await aesGcmDecrypt(key, nonce, data, WRAP_AAD);
  if (master.length !== 32) throw new Error('invalid_key_wrap');
  return master;
}

function recoverySecret(raw: Uint8Array): string {
  return `recovery:${toHex(raw)}`;
}

export async function createE2EEShareCrypto(
  mode: 'key' | 'password',
  password: string
): Promise<E2EEShareCrypto> {
  const masterKey = randomBytes(32);
  const recovery = generateRecoveryKey();
  const keyWrap = mode === 'password' ? await wrapMasterKey(masterKey, password) : '';
  const recoveryWrap = await wrapMasterKey(masterKey, recoverySecret(recovery.raw));
  return {
    masterKey,
    keyWrap,
    recoveryWrap,
    recoveryKey: recovery.formatted,
    keyFragment: toBase64Url(masterKey)
  };
}

export async function unwrapWithPassword(wrap: string, password: string): Promise<Uint8Array> {
  return unwrapMasterKey(wrap, password);
}

export async function unwrapWithRecovery(wrap: string, recoveryKey: string): Promise<Uint8Array> {
  const raw = normalizeRecoveryKey(recoveryKey);
  if (!raw) throw new Error('invalid_recovery_key');
  return unwrapMasterKey(wrap, recoverySecret(raw));
}

export function parseKeyFragment(hash: string): Uint8Array | null {
  if (!hash) return null;
  const params = new URLSearchParams(hash.replace(/^#/, ''));
  const value = params.get('key');
  if (!value) return null;
  return masterKeyFromInput(value);
}

export function masterKeyFromInput(value: string): Uint8Array | null {
  const trimmed = value.trim();
  if (!trimmed) return null;
  try {
    if (/^[0-9a-f]{64}$/i.test(trimmed)) return fromHex(trimmed);
    const raw = fromBase64Url(trimmed);
    if (raw.length === 32) return raw;
  } catch {
    // Try plain base64 as a convenience.
    try {
      const raw = fromBase64(trimmed);
      if (raw.length === 32) return raw;
    } catch {
      // ignore
    }
  }
  return null;
}

export function keyFragment(masterKey: Uint8Array): string {
  return `#key=${toBase64Url(masterKey)}`;
}

export function keyId(masterKey: Uint8Array): string {
  return toHex(masterKey.slice(0, 4));
}
