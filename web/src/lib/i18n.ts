export const dictionaries: Record<Locale, Record<string, string>> = { de, en };

function detect(): Locale {
  const stored = localStorage.getItem('texshare.locale');
  if (stored === 'de' || stored === 'en') return stored;
  const nav = (navigator.language || 'en').toLowerCase();
  return nav.startsWith('de') ? 'de' : 'en';
}

export const locale = writable<Locale>(detect());

locale.subscribe((value) => {
  localStorage.setItem('texshare.locale', value);
  document.documentElement.lang = value;
});

export function t(key: string, params?: Record<string, string | number>): string {
  let value = '';
  locale.subscribe((l) => {
    value = dictionaries[l][key] ?? dictionaries.en[key] ?? key;
  })();
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      value = value.replaceAll(`{${k}}`, String(v));
    }
  }
  return value;
}

export const tr = derived(locale, ($locale) => (key: string, params?: Record<string, string | number>) => {
  let value = dictionaries[$locale][key] ?? dictionaries.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      value = value.replaceAll(`{${k}}`, String(v));
    }
  }
  return value;
});

export function setLocale(next: Locale) {
  locale.set(next);
}

export function toggleLocale() {
  locale.update((l) => (l === 'de' ? 'en' : 'de'));
}
